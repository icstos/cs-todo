"""视图模型抽象：视图层唯一允许依赖的业务入口。

视图只做两件事：把原生事件翻译成这里的纯数据参数，把这里的只读状态渲染成控件。
任何"该不该保存 / 该显示哪句话 / 顺序怎么算"的判断都不在视图里。
"""
from __future__ import annotations

from collections.abc import Callable
from typing import Protocol, runtime_checkable

from models.events import Notice, Shortcut
from models.state import AppState, TaskDraft, ViewState

__all__ = ["TodoViewModel"]


@runtime_checkable
class TodoViewModel(Protocol):
    """待办应用视图模型契约。"""

    @property
    def state(self) -> AppState: ...

    @property
    def revision(self) -> int: ...

    @property
    def notice(self) -> Notice | None: ...

    @property
    def view(self) -> ViewState: ...

    def bind(self, listener: Callable[[], None] | None) -> None: ...

    def claim_notice(self) -> Notice | None: ...

    def bootstrap(self) -> None: ...

    def set_category(self, value: str) -> None: ...

    def set_status(self, value: str) -> None: ...

    def set_search_query(self, value: str) -> None: ...

    def focus_search(self) -> None: ...

    def toggle_focus(self) -> None: ...

    def open_add(self) -> None: ...

    def open_edit(self, task_id: int) -> None: ...

    def close_form(self) -> None: ...

    def save_form(self, draft: TaskDraft) -> None: ...

    def request_delete(self, task_id: int) -> None: ...

    def confirm_delete(self) -> None: ...

    def cancel_delete(self) -> None: ...

    def toggle_task(self, task_id: int) -> None: ...

    def reorder(self, old_index: int, new_index: int) -> None: ...

    def handle_escape(self) -> None: ...

    def on_shortcut(self, shortcut: Shortcut) -> None: ...
